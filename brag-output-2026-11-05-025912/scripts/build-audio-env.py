#!/usr/bin/env python3
"""Condense extract-audio-data.py output (first 24 s) into assets/audio-env.js.

Scenes sample window.__AUDIO_ENV at *build time* (while constructing their GSAP timeline) so every
frame stays a pure function of timeline time. bass = bands 0-1, treble = bands 6-7, both 0..1.
"""
import json
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "/tmp/audio-data.json"
dst = sys.argv[2] if len(sys.argv) > 2 else "composition/assets/audio-env.js"
seconds = 24

d = json.load(open(src))
fps = d["fps"]
frames = d["frames"][: seconds * fps]
rms = [round(f["rms"], 3) for f in frames]
bass = [round(max(f["bands"][0], f["bands"][1]), 3) for f in frames]
treble = [round(max(f["bands"][6], f["bands"][7]), 3) for f in frames]

cues = json.load(open("composition/assets/cues/happy-beats-business-moves-vol-10-by-ende-dot-app.music-cues.json"))
beats = [round(b["time"], 2) for b in cues["beats"] if b["time"] < seconds]

with open(dst, "w") as out:
    out.write("/* generated by scripts/build-audio-env.py from the bundled music bed */\n")
    out.write("window.__AUDIO_ENV = " + json.dumps({"fps": fps, "rms": rms, "bass": bass, "treble": treble}, separators=(",", ":")) + ";\n")
    out.write("window.__BEATS = " + json.dumps(beats) + ";\n")
    out.write(
        "window.__audioAt = function (arr, t) {\n"
        "  var i = Math.max(0, Math.min(arr.length - 1, Math.round(t * window.__AUDIO_ENV.fps)));\n"
        "  return arr[i];\n"
        "};\n"
    )
print("frames", len(rms), "max bass", max(bass), "max treble", max(treble), "max rms", max(rms))
